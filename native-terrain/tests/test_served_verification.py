"""Offline served-byte verification; no network or browser requests."""
from email.message import Message
import hashlib
import importlib.util
import io
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch
from urllib.error import HTTPError

MODULE = Path(__file__).resolve().parents[1] / 'deployment' / 'verify-served.py'
SPEC = importlib.util.spec_from_file_location('verify_served', MODULE)
VERIFY = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(VERIFY)

SECURITY_BODY = (b'<head><title>Not Acceptable!</title></head><body><h1>Not Acceptable!</h1>'
                 b'<p>An appropriate representation of the requested resource could not be '
                 b'found on this server. This error was generated by Mod_Security.</p></body></html>')


class Response(io.BytesIO):
    status = 200


class ServedVerificationTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.site = Path(self.temp.name)
        self.assets = {
            'living.html': b'<html><head><title>Living</title></head><body></body></html>',
            'living-app.mjs': b'export const version = "v3.1";',
        }
        for name, data in self.assets.items():
            (self.site / name).write_bytes(data)
        manifest = {'files': {name: hashlib.sha256(data).hexdigest() for name, data in self.assets.items()}}
        (self.site / 'manifest.json').write_text(json.dumps(manifest))
        self.assets['manifest.json'] = (self.site / 'manifest.json').read_bytes()
        self.release = 'https://example.test/aletheos/living-release-test/'
        self.entry = 'https://example.test/aletheos/living.html'

    def error(self, body=SECURITY_BODY, status=406):
        headers = Message()
        headers['Content-Type'] = 'text/html; charset=utf-8'
        headers['Server'] = 'test-server'
        headers['Set-Cookie'] = 'do-not-log=this'
        return HTTPError(self.release + 'living.html', status, 'Not Acceptable', headers, io.BytesIO(body))

    def successful_open(self, request, timeout):
        if request.full_url == self.entry:
            data = self.assets['living.html'].replace(b'<head>', b'<head><base href="./living-release-test/">')
        else:
            data = self.assets[request.full_url.removeprefix(self.release)]
        self.assertEqual(timeout, 30)
        self.assertEqual(dict(request.header_items()), {'Cache-control': 'no-cache'})
        return Response(data)

    def test_success_checks_exact_manifest_assets_and_activated_entry(self):
        with patch.object(VERIFY, 'urlopen', side_effect=self.successful_open) as opened:
            result = VERIFY.verify_site(self.site, self.release, self.entry)
        self.assertTrue(result['passed'])
        self.assertTrue(result['complete'])
        self.assertEqual(result['files_checked'], 3)
        self.assertEqual(result['files_verified'], 3)
        self.assertTrue(result['entry_verified'])
        self.assertEqual(opened.call_count, 4)
        self.assertEqual(result['not_checked'], [])
        self.assertFalse(result['browser_verified'])

    def test_explicit_security_rejection_stops_without_retry_or_header_change(self):
        with patch.object(VERIFY, 'urlopen', side_effect=self.error()) as opened:
            result = VERIFY.verify_site(self.site, self.release, self.entry)
        self.assertEqual(opened.call_count, 1)
        request = opened.call_args.args[0]
        self.assertEqual(dict(request.header_items()), {'Cache-control': 'no-cache'})
        self.assertFalse(result['passed'])
        self.assertFalse(result['complete'])
        self.assertTrue(result['stopped_early'])
        self.assertEqual(result['files_checked'], 1)
        self.assertEqual(result['files_verified'], 0)
        self.assertEqual(result['files_skipped'], 2)
        self.assertFalse(result['entry_checked'])
        self.assertEqual(result['not_checked'], ['living-app.mjs', 'manifest.json', 'public living.html'])
        failure = result['failures'][0]
        self.assertEqual(failure['http_status'], 406)
        self.assertEqual(failure['content_type'], 'text/html; charset=utf-8')
        self.assertEqual(failure['server'], 'test-server')
        self.assertEqual(failure['body_excerpt'], SECURITY_BODY.decode())
        self.assertTrue(failure['explicit_security_rejection'])
        self.assertNotIn('do-not-log', json.dumps(result))

    def test_error_excerpt_is_bounded_and_marks_truncation(self):
        body = SECURITY_BODY + b'x' * (VERIFY.MAX_ERROR_BODY_BYTES * 3)
        with patch.object(VERIFY, 'urlopen', side_effect=self.error(body)):
            result = VERIFY.verify_site(self.site, self.release)
        failure = result['failures'][0]
        self.assertEqual(len(failure['body_excerpt']), VERIFY.MAX_ERROR_BODY_BYTES)
        self.assertTrue(failure['body_truncated'])

    def test_generic_406_is_reported_without_inventing_security_classification(self):
        replies = [self.error(b'No acceptable representation.'),
                   Response(self.assets['living-app.mjs']), Response(self.assets['manifest.json'])]
        with patch.object(VERIFY, 'urlopen', side_effect=replies) as opened:
            result = VERIFY.verify_site(self.site, self.release)
        self.assertEqual(opened.call_count, 3)
        self.assertTrue(result['complete'])
        self.assertFalse(result['passed'])
        self.assertFalse(result['failures'][0]['explicit_security_rejection'])
        self.assertIsNone(result['stop_reason'])
        self.assertEqual(result['files_verified'], 2)

    def test_successful_responses_with_wrong_bytes_never_pass(self):
        with patch.object(VERIFY, 'urlopen', side_effect=lambda *a, **k: Response(b'incorrect bytes')):
            result = VERIFY.verify_site(self.site, self.release, self.entry)
        self.assertTrue(result['complete'])
        self.assertFalse(result['passed'])
        self.assertEqual(result['files_verified'], 0)
        self.assertFalse(result['entry_verified'])
        self.assertEqual(len(result['failures']), 4)

    def test_entry_security_rejection_retains_successful_asset_checks(self):
        replies = [Response(data) for data in self.assets.values()] + [self.error()]
        with patch.object(VERIFY, 'urlopen', side_effect=replies) as opened:
            result = VERIFY.verify_site(self.site, self.release, self.entry)
        self.assertEqual(opened.call_count, 4)
        self.assertTrue(result['complete'])
        self.assertEqual(result['files_verified'], 3)
        self.assertTrue(result['entry_checked'])
        self.assertFalse(result['entry_verified'])
        self.assertFalse(result['passed'])
        self.assertEqual(result['stop_reason'], 'explicit_security_rejection')


if __name__ == '__main__':
    unittest.main()
