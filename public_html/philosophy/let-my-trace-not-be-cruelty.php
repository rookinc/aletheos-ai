      <h2>An agnostic horizon</h2>
      <p class="section-text">
        I also wonder whether my life could be received by some witness beyond
        the horizon of what I can know. I can imagine such a possibility. I
        cannot turn that act of imagination into proof that the witness exists,
        or claim to know what memory, empathy, or suffering would mean to it.
      </p>
      <p class="section-text">
        I remain agnostic about that witness. Devoutly agnostic: the question
        matters too much to answer cheaply. If my existence could become
        experience for another beyond my understanding, I would want that
        encounter to contain less cruelty. This is an extension of my ethical
        concern into uncertainty.
      </p>
      <p class="section-text">
        The people and animals around me already give me sufficient reason
        to care. My responsibility to them does not wait for a cosmic answer.
        The possible witness is a further horizon of the question, while the
        local relationship is already here, asking something of me.
      </p>
