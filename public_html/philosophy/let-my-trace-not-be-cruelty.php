      <h2>I carry what has reached me</h2>
      <p class="section-text">
        I remember, therefore I was. I offer that as a way of locating myself
        within a life already underway. Memory can distort, fail, soften, or
        wound. It gives me traces to work with, including traces I may
        misunderstand. My certainty about a memory cannot guarantee that my
        account of an event is correct.
      </p>
      <p class="section-text">
        In my interpretation, remembering reaches beyond the stories I can
        consciously recall. Inheritance, nourishment, injury, repair, skill,
        habit, language, and touch have helped give my life its form. When I
        describe the body as remembering, I am drawing attention to this
        accumulated history. I am using a philosophical language of continuity,
        rather than treating every lasting change as the same kind of memory.
      </p>
      <p class="section-text">
        My conclusions take shape within that history. They influence what I
        expect, whom I trust, what I fear, and which possibilities I notice.
        I may be wrong about the world, and the wrongness can still have
        consequences through the way I act.
      </p>
